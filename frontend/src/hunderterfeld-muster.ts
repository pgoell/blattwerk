function join(rows: string[]): string {
  return rows.join("");
}

// The hidden cells of a picture, in order. An unknown name is the heart.
export function musterCells(name: string): number[] {
  const bits = BITS[name as MusterName] ?? BITS.herz;
  const cells: number[] = [];
  for (let i = 0; i < bits.length; i++) if (bits[i] === "#") cells.push(i);
  return cells;
}
